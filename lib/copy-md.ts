// Builds COPY.md from copy.ts: every fixed string a screen can show, in one
// place a person can read without opening the code.
import { copy } from './copy';

// What to put in a string that needs a name or a number, so it reads like the
// real thing. Numbers get two examples, to show the singular and the plural.
const SAMPLE: Record<string, unknown[]> = {
  firstName: ['Test'],
  name: ['Test M.'],
  names: ['Test M., Test L.'],
  time: ['4:32 PM'],
  when: ['Wed, Nov 18 4:32 PM'],
  day: ['Wed, Nov 18'],
  since: ['Wed, Nov 18'],
  message: ['The task needs a title'],
  max: [120],
  n: [1, 3],
  seconds: [1, 12],
  dimMinutes: [60, 20],
};
const NUMBER_PAIRS: Record<string, [number[], number[]]> = {
  'attended,meetings,since': [[1, 1], [7, 9]],
  'added,skipped': [[5, 0], [5, 2]],
  'done,total': [[1, 4], [3, 4]],
};

function paramNames(fn: (...args: never[]) => unknown): string[] {
  const source = fn.toString().trim();
  // Build tools write a one-parameter arrow function with or without brackets.
  const bare = /^([A-Za-z_$][\w$]*)\s*=>/.exec(source);
  if (bare) return [bare[1]];
  const inside = source.slice(source.indexOf('(') + 1, source.indexOf(')'));
  return inside.split(',').map((p) => p.trim().split(/[:=\s]/)[0]).filter(Boolean);
}

// Strings whose sample value should be the real limit or a fitting name.
const KEY_SAMPLE: Record<string, unknown[]> = {
  'errors.taskTitleLong': [120],
  'errors.taskDescriptionLong': [2000],
  'errors.taskStepsMany': [12],
  'errors.taskStepLong': [200],
  'errors.nameLong': [60],
  'tasks.forSubteam': ['Build'],
  'tasks.subteamAlso': ['Assembly, CAD'],
  'members.subteamPartOf': ['Build'],
  'inventory.summary': [152, 148],
};

function examples(fn: (...args: never[]) => unknown, path: string): string[] {
  const names = paramNames(fn);
  const call = fn as unknown as (...args: unknown[]) => string | string[];
  if (KEY_SAMPLE[path]) return [call(...KEY_SAMPLE[path])].flat();
  const pair = NUMBER_PAIRS[names.join(',')];
  if (pair) {
    return pair.map((numbers) => call(...names.map((name, i) => (i < numbers.length ? numbers[i] : SAMPLE[name]?.[0])))).flat();
  }
  const variants = Math.max(...names.map((name) => SAMPLE[name]?.length ?? 1));
  const out: (string | string[])[] = [];
  for (let v = 0; v < variants; v++) {
    out.push(call(...names.map((name) => (SAMPLE[name] ?? [`{${name}}`])[Math.min(v, (SAMPLE[name]?.length ?? 1) - 1)])));
  }
  // A string that is really a short list (set-up steps, say) comes back as an array.
  return [...new Set(out.flat())];
}

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function buildCopyMd(): string {
  const lines = [
    '# Every fixed string in the app',
    '',
    'Built from `lib/copy.ts` by `npm run copy:md`. Do not edit this file by hand: change `lib/copy.ts` and build it again. A test fails if the two disagree.',
    '',
    'Strings with a name or a number in them are shown with sample values, once for one and once for many where that changes the wording.',
    '',
  ];
  for (const [section, entries] of Object.entries(copy)) {
    lines.push(`## ${section}`, '', '| Key | Text |', '|---|---|');
    for (const [key, value] of Object.entries(entries as Record<string, unknown>)) {
      const texts =
        typeof value === 'function'
          ? examples(value as (...args: never[]) => unknown, `${section}.${key}`)
          : Array.isArray(value)
            ? value.map(String)
            : [String(value)];
      lines.push(`| \`${key}\` | ${texts.map(cell).join('<br>')} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}
